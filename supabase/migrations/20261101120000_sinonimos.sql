-- Sinônimos do vocabulário único, em português do Brasil e nas variações em inglês que a
-- comunidade usa. Cada termo aponta para o nome oficial da habilidade ou função, e não para o
-- identificador, porque os identificadores podem diferir entre os ambientes. Nome que não existir
-- num ambiente é ignorado.
--
-- A comparação passa a ignorar acentos e maiúsculas: "animacao", "Animação" e "ANIMAÇÃO" são o
-- mesmo termo. A lista é a primeira versão: os termos novos virão das buscas que não acharem nada.

create function oportunidades.normalizar_termo(p_texto text)
returns text
language sql
immutable
parallel safe
set search_path = ''
as $$
  select lower(translate(btrim(p_texto),
    'ÁÀÂÃÄáàâãäÉÈÊËéèêëÍÌÎÏíìîïÓÒÔÕÖóòôõöÚÙÛÜúùûüÇçÑñ',
    'AAAAAaaaaaEEEEeeeeIIIIiiiiOOOOOoooooUUUUuuuuCcNn'))
$$;

revoke all on function oportunidades.normalizar_termo(text) from public, anon, authenticated;
grant execute on function oportunidades.normalizar_termo(text) to service_role;

comment on function oportunidades.normalizar_termo(text) is 'Termo sem espaços nas pontas, sem acentos e em minúsculas, para comparar buscas e sinônimos.';

-- A coluna normalizada passa a ignorar acentos. O índice único que dependia dela cai junto e volta abaixo.
alter table oportunidades.sinonimos drop column termo_normalizado;
alter table oportunidades.sinonimos
  add column termo_normalizado text generated always as (oportunidades.normalizar_termo(termo)) stored;

create unique index sinonimos_termo_alvo_idx
  on oportunidades.sinonimos (termo_normalizado, coalesce(habilidade_id, tipo_funcao_id));
create index sinonimos_termo_normalizado_idx on oportunidades.sinonimos (termo_normalizado);

